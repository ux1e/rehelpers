#pragma once

// Класс и фабрика намеренно объявлены здесь, а определены в greeter.cpp —
// отдельной единице трансляции. Это не просто стиль: если бы определение
// класса и вызов g.greet() были видны компилятору одновременно в одном .cpp,
// GCC/Clang на -O2 девиртуализировали бы вызов (подставили бы прямой адрес
// функции вместо обращения через vtable) — и хук из vtable_hook.hpp
// оказался бы никак не виден в рантайме. Разделение на TU — самый простой
// способ честно показать именно рантайм-перехват, а не оптимизированный
// компилятором прямой вызов.

struct Greeter {
    virtual void greet();
    virtual ~Greeter();
};

Greeter* make_greeter();
